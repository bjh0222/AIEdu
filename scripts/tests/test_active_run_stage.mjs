import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import vm from 'node:vm';
const root = path.resolve(import.meta.dirname, '../..');
const require = createRequire(path.join(root,'apps/web/package.json'));
const ts = require('typescript');
const source = fs.readFileSync(path.join(root,'apps/web/lib/v2/status.ts'),'utf8');
const js = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const context = {exports:{}};
vm.runInNewContext(js,context);
const {activeRunStage,stageText}=context.exports;
const run={state:'running',stages:{generating:'running',checking:'running'},calls:[{stage:'blind_solving',status:'sent'}]};
assert.equal(activeRunStage(run),'checking');
assert.equal(activeRunStage({...run,calls:[{stage:'generating',status:'sent'}]}),'generating');
assert.equal(activeRunStage({...run,calls:[]}),'checking');
assert.equal(activeRunStage({...run,state:'completed'}),undefined);
assert.equal(activeRunStage({state:'queued',stages:{},calls:[]}),undefined);
assert.equal(stageText('running'),'进行中');
console.log('active stage regression: 6 passed');
